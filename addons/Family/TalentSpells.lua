-- Which spell each talent is. GENERATED - see tools/talents.py.
--
-- Talents were the one thing Family stored as a word rather than an id, because
-- GetTalentInfo answers only for the class being played: a mage cannot ask what the
-- third talent in a warlock's second tree is called, and showing another member's
-- talents is the whole point of that panel. So a member recorded on a German client
-- showed German talent names on an English one.
--
-- A talent is a spell, and the client will name any spell for any class without
-- loading anything first. So there are no names here at all: a position maps to the
-- spell id of the talent's first rank, and every reader's own client says what it is
-- called - in all eleven languages the game ships in, not the five Family writes.
--
-- Mists is the same idea in a different shape and is below, keyed by the talent id
-- its client reports rather than by a position: it is six tiers of three chosen one
-- from each, and the id is what Family records.
--
-- Keyed by expansion, because Era and Burning Crusade disagree about 32 of the 419
-- positions they share: Blizzard moved talents between them, and one merged table
-- would name those 32 wrongly on one of the two clients.
--
-- Tiers and columns count from one here, as the client reports them and as the panel
-- draws them. The table they came from counts from zero.

