-- What to call a talent, in the language of whoever is reading.
--
-- The position is what Family records - which tree, which tier, which column - and the table
-- above turns that into the spell the talent is. The client will name any spell, for any
-- class, which is the whole reason this works where asking about the talent itself does not.
--
-- Falls back to the word the recording client wrote, which is what every record made before
-- this table existed carries, and is still better than a blank.
function Family:TalentName(classFile, tab, tier, column, recorded)
	local expansion = Family.Capabilities and Family.Capabilities.expansion
	local byClass = expansion and Family.TalentSpells[expansion]
	local tabs = byClass and classFile and byClass[classFile]
	local tiers = tabs and tab and tabs[tab]
	local columns = tiers and tier and tiers[tier]
	local id = columns and column and columns[column]

	if id then
		local name = Family.Names:Spell(id)
		if type(name) == "string" and name ~= "" then return name end
	end

	return recorded
end

-- What a class calls one of its three trees, in the reader's language.
--
-- The one part of this that is a name rather than an id, because a tree has no spell to be
-- named from. Falls back to the word the recording client wrote, which is right for a client
-- whose language this does not ship and for anything newer than the table.
function Family:TalentTreeName(classFile, tab, recorded)
	local expansion = Family.Capabilities and Family.Capabilities.expansion
	local byClass = expansion and Family.TalentTrees[expansion]
	local tabs = byClass and classFile and byClass[classFile]
	local names = tabs and tab and tabs[tab]
	local name = names and (names[Family.locale] or names.enUS)

	if type(name) == "string" and name ~= "" then return name end
	return recorded
end

-- The same question on Mists, where a talent has an id of its own and needs no position at
-- all: the id is the spell. The client names any spell for any class, so this is the same
-- answer as the grid above by a shorter road.
function Family:TalentNameByID(id, recorded)
	local spell = id and Family.TalentSpellByID[id]
	if spell then
		local name = Family.Names:Spell(spell)
		if type(name) == "string" and name ~= "" then return name end
	end
	return recorded
end
